import os, re, time, glob
import build_light_theme as B


def admin_templates():
    names = set(["admin_login.html", "admin_setup.html", "forgot_password.html", "admin_dashboard.html",
                 "add_car.html", "edit_car.html", "bookings.html", "inquiries.html", "manage_admins.html",
                 "change_password.html", "sell_requests.html", "swap_requests.html"])
    for f in glob.glob("templates/admin*.html"):
        names.add(os.path.basename(f))
    return sorted(n for n in names if os.path.exists(os.path.join("templates", n)))


def main():
    B.main()
    names = admin_templates()
    css = ""
    if os.path.exists("static/css/admin-polish.css"):
        css += B.clean(open("static/css/admin-polish.css", encoding="utf-8").read())
    for n in names:
        t = open(os.path.join("templates", n), encoding="utf-8").read()
        for blk in re.findall(r"<style[^>]*>(.*?)</style>", t, flags=re.S):
            css += "\n" + B.clean(blk)
    gen = B.process(css)
    old = B.PUBLIC_TEMPLATES
    B.PUBLIC_TEMPLATES = names
    inl = B.inline_rules()
    B.PUBLIC_TEMPLATES = old
    head = "/* Admin light theme - generated by build_light_admin.py */\n"
    open("static/css/light-admin.css", "w", encoding="utf-8").write(head + gen + "\n" + inl + "\n")
    ts = str(int(time.time()))
    p = "templates/_theme_head.html"
    if os.path.exists(p):
        t = open(p, encoding="utf-8").read()
        t2 = re.sub(r"(light-(?:theme|admin)\.css'\) \}\}\?v=)\d+", lambda m: m.group(1) + ts, t)
        if t2 != t:
            open(p, "w", encoding="utf-8").write(t2)
    print("admin light theme: %d rules + %d inline rules -> static/css/light-admin.css" % (gen.count("}\n") + 1, inl.count("\n") + (1 if inl else 0)))


if __name__ == "__main__":
    main()
